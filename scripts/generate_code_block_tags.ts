// Writes `src/code_block_tags/linguist_generated.rs`, the table of the code
// block tags the plugin knows the file extension of beyond the ones it maps
// itself. It's made from GitHub Linguist's list of languages, which is also
// what GitHub picks the language of a fenced code block from: each language's
// name and aliases map to its primary extension. Run it with
// `deno run -A scripts/generate_code_block_tags.ts` after updating
// `LINGUIST_VERSION` to a newer release of Linguist.

import { parse } from "jsr:@std/yaml@1.3.0";
import $ from "npm:dax@0.50.1";

const LINGUIST_VERSION = "v9.7.0";

interface Language {
  aliases?: string[];
  extensions?: string[];
}

const languagesYaml = await $.request(
  `https://raw.githubusercontent.com/github-linguist/linguist/${LINGUIST_VERSION}/lib/linguist/languages.yml`,
).text();
const languages = parse(languagesYaml) as Record<string, Language>;

const extensionsByTag = new Map<string, string>();
for (const [name, language] of Object.entries(languages)) {
  const extension = language.extensions?.[0]?.replace(/^\./, "").toLowerCase();
  if (extension == null) {
    continue;
  }
  for (const tag of [name, ...(language.aliases ?? [])].map((tag) => tag.toLowerCase())) {
    // a tag is the first word of a code fence's info string, so it can't have whitespace
    if (/\s/.test(tag)) {
      continue;
    }
    // the languages are sorted by name, so the first one with a tag keeps it
    if (!extensionsByTag.has(tag)) {
      extensionsByTag.set(tag, extension);
    }
  }
}

// sorted by the bytes of the tag, the same as rust compares strings, so a tag
// can be looked up by binary search
const encoder = new TextEncoder();
const compareBytes = (a: string, b: string) => {
  const aBytes = encoder.encode(a);
  const bBytes = encoder.encode(b);
  for (let i = 0; i < Math.min(aBytes.length, bBytes.length); i++) {
    if (aBytes[i] !== bBytes[i]) {
      return aBytes[i] - bBytes[i];
    }
  }
  return aBytes.length - bBytes.length;
};
const entries = [...extensionsByTag].sort(([a], [b]) => compareBytes(a, b));
const rows = entries
  .map(([tag, extension]) => `  (${JSON.stringify(tag)}, ${JSON.stringify(extension)}),`)
  .join("\n");

const text = `// @generated by scripts/generate_code_block_tags.ts -- do not edit by hand
//
// From the list of languages of GitHub Linguist ${LINGUIST_VERSION}
// (https://github.com/github-linguist/linguist), which is under the MIT license:
// Copyright (c) 2017 GitHub, Inc.

/// The lowercase code block tags GitHub Linguist knows, which are the name and
/// aliases of each of its languages, and the primary file extension of the
/// language, sorted by tag so that a tag can be looked up by binary search.
#[rustfmt::skip]
pub(super) static LINGUIST_TAG_EXTENSIONS: [(&str, &str); ${entries.length}] = [
${rows}
];
`;

$.path(import.meta.dirname!).join("../src/code_block_tags/linguist_generated.rs").writeTextSync(text);
$.log(`Wrote ${entries.length} tags from Linguist ${LINGUIST_VERSION}.`);
